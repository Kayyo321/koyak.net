#!/usr/bin/env node
/* Seal (encrypt) the private story pack for the Worker, and manage its key without ever printing it.
     node scripts/seal-story.mjs keygen   create STORY_PACK_KEY in .dev.vars (only if it isn't there)
     node scripts/seal-story.mjs seal     private/story-pack.mjs -> worker/story/pack.sealed.js (AES-256-GCM)
     node scripts/seal-story.mjs check    the sealed pack opens with the local key and matches the plaintext
     node scripts/seal-story.mjs unseal   recover the plaintext pack to private/story-pack.recovered.json
     node scripts/seal-story.mjs key      write the key to stdout, for piping into `wrangler secret put` only
   The key lives in .dev.vars (git-ignored) locally and in the Worker secret STORY_PACK_KEY in production. */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { webcrypto as crypto } from "node:crypto";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const VARS = join(ROOT, ".dev.vars");
const PLAIN = join(ROOT, "private", "story-pack.mjs");
const SEALED = join(ROOT, "worker", "story", "pack.sealed.js");
const V = 1, AAD = new TextEncoder().encode("koyak-story-pack/v" + V);
const b64 = (u8) => Buffer.from(u8).toString("base64");

function readKey() {
  if (process.env.STORY_PACK_KEY) return process.env.STORY_PACK_KEY.trim();
  if (!existsSync(VARS)) return null;
  const m = /^STORY_PACK_KEY\s*=\s*"?([A-Za-z0-9+/=]+)"?\s*$/m.exec(readFileSync(VARS, "utf8"));
  return m ? m[1] : null;
}
async function aes(keyB64, usage) {
  const raw = Buffer.from(keyB64, "base64");
  if (raw.length !== 32) throw new Error("STORY_PACK_KEY must be 32 bytes, base64");
  return crypto.subtle.importKey("raw", raw, "AES-GCM", false, [usage]);
}
async function plaintext() {
  const mod = await import(pathToFileURL(PLAIN).href + "?t=" + Date.now());
  return JSON.stringify(mod.default);
}
async function open(keyB64) {
  const src = readFileSync(SEALED, "utf8");
  const sealed = JSON.parse(src.slice(src.indexOf("{"), src.lastIndexOf("}") + 1));
  const plain = await crypto.subtle.decrypt({ name: "AES-GCM", iv: Buffer.from(sealed.iv, "base64"), additionalData: AAD },
    await aes(keyB64, "decrypt"), Buffer.from(sealed.ct, "base64"));
  return new TextDecoder().decode(plain);
}

const cmd = process.argv[2];
const key = readKey();
if (cmd === "keygen") {
  if (key) { console.log("STORY_PACK_KEY already set in .dev.vars (left unchanged)"); process.exit(0); }
  const k = b64(crypto.getRandomValues(new Uint8Array(32)));
  const prev = existsSync(VARS) ? readFileSync(VARS, "utf8").replace(/\n*$/, "\n") : "";
  writeFileSync(VARS, prev + `STORY_PACK_KEY=${k}\n`, { mode: 0o600 });
  console.log("wrote a new STORY_PACK_KEY to .dev.vars (not shown). Back it up somewhere private: without it the sealed pack can't be opened.");
} else if (cmd === "seal") {
  if (!key) throw new Error("no STORY_PACK_KEY: run `node scripts/seal-story.mjs keygen` first");
  const iv = crypto.getRandomValues(new Uint8Array(12));
  const ct = await crypto.subtle.encrypt({ name: "AES-GCM", iv, additionalData: AAD }, await aes(key, "encrypt"), new TextEncoder().encode(await plaintext()));
  writeFileSync(SEALED, "// Generated by scripts/seal-story.mjs. Encrypted (AES-256-GCM); the key is the Worker secret STORY_PACK_KEY.\n" +
    `export const SEALED = ${JSON.stringify({ v: V, iv: b64(iv), ct: b64(new Uint8Array(ct)) })};\n`);
  console.log(`sealed ${SEALED.replace(ROOT + "/", "")} (${(ct.byteLength / 1024).toFixed(1)} KB)`);
} else if (cmd === "check") {
  if (!key) throw new Error("no STORY_PACK_KEY");
  const opened = await open(key);
  const same = existsSync(PLAIN) ? opened === (await plaintext()) : null;
  console.log("sealed pack opens: yes" + (same === null ? "" : same ? "; matches private/story-pack.mjs" : "; OUT OF DATE, run seal"));
  if (same === false) process.exit(1);
} else if (cmd === "unseal") {
  if (!key) throw new Error("no STORY_PACK_KEY");
  writeFileSync(join(ROOT, "private", "story-pack.recovered.json"), JSON.stringify(JSON.parse(await open(key)), null, 2));
  console.log("wrote private/story-pack.recovered.json");
} else if (cmd === "key") {
  if (!key) throw new Error("no STORY_PACK_KEY");
  process.stdout.write(key);
} else {
  console.log("usage: node scripts/seal-story.mjs keygen|seal|check|unseal|key");
  process.exit(2);
}
